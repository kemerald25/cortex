  for all using (auth.uid() = user_id);

-- Similarity Match function for pgvector
create or replace function public.match_chunks (
  query_embedding vector(1024),
  match_threshold float,
  match_count int,
  p_topic_id uuid
)
returns table (
  id uuid,
  content text,
  material_id uuid,
  addition_id uuid,
  similarity float
)
language sql stable
as $$
  select
    chunks.id,
    chunks.content,
    chunks.material_id,
    chunks.addition_id,
    1 - (chunks.embedding <=> query_embedding) as similarity
  from chunks
  where chunks.topic_id = p_topic_id
    and 1 - (chunks.embedding <=> query_embedding) > match_threshold
  order by chunks.embedding <=> query_embedding
  limit match_count;
$$;
