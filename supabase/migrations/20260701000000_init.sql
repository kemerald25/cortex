-- Profiles Policies
create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);
create policy "Users can insert own profile" on public.profiles
  for insert with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

-- Courses Policies
create policy "Users can access own courses" on public.courses
  for all using (auth.uid() = user_id);

-- Materials Policies
create policy "Users can access materials of own courses" on public.materials
  for all using (
    exists (
      select 1 from public.courses
      where courses.id = materials.course_id
        and courses.user_id = auth.uid()
    )
  );

-- Topics Policies
create policy "Users can access topics of own courses" on public.topics
  for all using (
    exists (
      select 1 from public.courses
      where courses.id = topics.course_id
        and courses.user_id = auth.uid()
    )
  );

-- Additions Policies
create policy "Users can access own additions" on public.additions
  for all using (auth.uid() = user_id);

-- Chunks Policies
create policy "Users can access chunks of own courses" on public.chunks
  for all using (
    exists (
      select 1 from public.topics
      join public.courses on courses.id = topics.course_id
      where topics.id = chunks.topic_id
        and courses.user_id = auth.uid()
    ) or exists (
      select 1 from public.materials
      join public.courses on courses.id = materials.course_id
      where materials.id = chunks.material_id
        and courses.user_id = auth.uid()
    )
  );

-- Notes Policies
create policy "Users can access notes of own courses" on public.notes
  for all using (
    exists (
      select 1 from public.topics
      join public.courses on courses.id = topics.course_id
      where topics.id = notes.topic_id
        and courses.user_id = auth.uid()
    )
  );

-- Flashcards Policies
create policy "Users can access flashcards of own courses" on public.flashcards
  for all using (
    exists (
      select 1 from public.topics
      join public.courses on courses.id = topics.course_id
      where topics.id = flashcards.topic_id
        and courses.user_id = auth.uid()
    )
