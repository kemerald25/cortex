-- Enable pgvector extension
create extension if not exists vector;

-- Profiles Table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  academic_level text not null, -- '100L', '200L', '300L', '400L', '500L'
  created_at timestamp with time zone default now()
);

-- Courses Table
create table if not exists public.courses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users on delete cascade not null,
  name text not null,
  code text not null,
  level text not null,
  created_at timestamp with time zone default now()
);

-- Materials Table
create table if not exists public.materials (
  id uuid primary key default gen_random_uuid(),
  course_id uuid references public.courses on delete cascade not null,
  name text not null,
  type text not null, -- 'textbook' | 'past questions' | 'slides' | 'notes'
  file_path text, -- Supabase storage path
  extracted_text text,
  status text not null default 'pending', -- 'pending' | 'extracting' | 'completed' | 'failed'
  created_at timestamp with time zone default now()
);

-- Topics Table (unconfirmed by default, confirmed when TOC is finalized)
create table if not exists public.topics (
  id uuid primary key default gen_random_uuid(),
  course_id uuid references public.courses on delete cascade not null,
  title text not null,
  description text,
  order_index integer not null default 0,
  is_confirmed boolean not null default false,
  created_at timestamp with time zone default now()
);

-- Additions Table (User's custom notes/photos per topic)
create table if not exists public.additions (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid references public.topics on delete cascade not null,
  user_id uuid references auth.users on delete cascade not null,
  type text not null, -- 'text' | 'image'
  content text, -- Typed text or OCR text
  file_path text, -- If photo upload
  created_at timestamp with time zone default now()
);

-- Chunks Table (stores embeddings for similarity searches)
create table if not exists public.chunks (
  id uuid primary key default gen_random_uuid(),
  material_id uuid references public.materials on delete cascade, -- Nullable for additions
  addition_id uuid references public.additions on delete cascade, -- Nullable for materials
  topic_id uuid references public.topics on delete cascade, -- Nullable until topic confirmed
  content text not null,
  embedding vector(1024), -- Cloudflare bge-large-en-v1.5 has 1024 dims
  created_at timestamp with time zone default now()
);

-- Notes Table (1 per confirmed topic, generated by AI)
create table if not exists public.notes (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid references public.topics on delete cascade unique not null,
  core_idea text not null,
  key_definitions jsonb not null, -- array of { term: string, definition: string }
  process_logic text not null,
  formula text,
  exam_angles text not null,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Flashcards Table (SRS enabled)
create table if not exists public.flashcards (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid references public.topics on delete cascade not null,
  question text not null,
  answer text not null,
  ease_factor double precision not null default 2.5,
  interval integer not null default 0, -- in days
  repetitions integer not null default 0,
  next_review_date timestamp with time zone not null default now(),
  source text not null, -- 'ai' | 'user'
  created_at timestamp with time zone default now()
);

-- Chat Messages Table
create table if not exists public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid references public.topics on delete cascade not null,
  user_id uuid references auth.users on delete cascade not null,
  role text not null, -- 'user' | 'assistant'
  content text not null,
  created_at timestamp with time zone default now()
);

